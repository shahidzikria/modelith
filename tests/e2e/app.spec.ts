import { expect, test, type Page } from '@playwright/test';

async function fresh(page: Page) {
  await page.goto('/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
}

const palette = (page: Page, label: string) => page.getByRole('navigation', { name: 'Block palette' }).getByRole('button', { name: label, exact: true });
const node = (page: Page, text: string) => page.locator('.react-flow__node').filter({ hasText: text });

async function connect(page: Page, from: string, to: string) {
  await page.waitForTimeout(350); // let node measurement / viewport settle
  const a = (await node(page, from).locator('.react-flow__handle-right').boundingBox())!;
  const b = (await node(page, to).locator('.react-flow__handle-left').first().boundingBox())!;
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
  await page.mouse.down();
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 12 });
  await page.mouse.up();
}

test('empty canvas shows the template gallery', async ({ page }) => {
  await fresh(page);
  await expect(page.getByRole('heading', { name: 'Start from a template' })).toBeVisible();
  await expect(page.getByRole('button', { name: /YOLOv8-s style/ })).toBeVisible();
});

test('click-to-append builds a classifier and generates code', async ({ page }) => {
  await fresh(page);
  await page.getByRole('button', { name: /Empty canvas/ }).click();
  for (const label of ['Image', 'Conv·BN·Act', 'Global average pool', 'Classification head']) await palette(page, label).click();
  await expect(page.locator('.react-flow__node')).toHaveCount(4);
  await expect(page.locator('.react-flow__edge')).toHaveCount(3);
  await expect(node(page, 'Conv·BN·Act')).toContainText('64×224×224');

  await page.getByRole('tab', { name: 'Summary' }).click();
  await expect(page.getByText('ready to generate')).toBeVisible();

  await page.getByRole('button', { name: /Generate code/ }).click();
  await expect(page.locator('.monaco-editor')).toContainText('PyTorch model generated by Netloom', { timeout: 20_000 });
  await page.getByRole('button', { name: 'Copy file' }).click();
  const clip = await page.evaluate(() => navigator.clipboard.readText());
  expect(clip).toContain('class GeneratedModel(nn.Module)');
  expect(clip).toContain('ClassificationHead(64, 10)');
});

test('drag from palette, connect ports and edit a parameter', async ({ page }) => {
  await fresh(page);
  await page.getByRole('button', { name: /Empty canvas/ }).click();
  const pane = page.locator('.react-flow__pane');
  const box = (await pane.boundingBox())!;
  await palette(page, 'Image').dragTo(pane, { targetPosition: { x: 150, y: 200 } });
  await palette(page, 'Conv2d').dragTo(pane, { targetPosition: { x: Math.min(box.width - 150, 520), y: 200 } });
  await expect(page.locator('.react-flow__node')).toHaveCount(2);
  await expect(page.locator('.react-flow__edge')).toHaveCount(0);

  await connect(page, 'Image', 'Conv2d');
  await expect(page.locator('.react-flow__edge')).toHaveCount(1);
  await expect(node(page, 'Conv2d')).toContainText('64×224×224');

  await node(page, 'Conv2d').click({ position: { x: 60, y: 14 } });
  await page.getByLabel('Stride', { exact: true }).fill('2');
  await expect(node(page, 'Conv2d')).toContainText('64×112×112');

  // Incompatible connections are refused with an explanation.
  await palette(page, 'Embedding').click();
  await connect(page, 'Conv2d', 'Embedding');
  await expect(page.getByRole('status')).toContainText('needs token ids, got a feature map');
});

test('undo / redo and delete', async ({ page }) => {
  await fresh(page);
  await page.getByRole('button', { name: /Simple CNN classifier/ }).click();
  const count = await page.locator('.react-flow__node').count();
  await node(page, 'Global average pool').click();
  await page.keyboard.press('Delete');
  await expect(page.locator('.react-flow__node')).toHaveCount(count - 1);
  await page.keyboard.press('Control+z');
  await expect(page.locator('.react-flow__node')).toHaveCount(count);
  await page.keyboard.press('Control+Shift+z');
  await expect(page.locator('.react-flow__node')).toHaveCount(count - 1);
});

