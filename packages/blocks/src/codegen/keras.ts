import { formatCount, pyShape } from '../shapes';
import { py } from '../py';
import { kerasHelpers, resolveHelpers } from '../helpers/registry';
import { isUnsupported, type EmitCtx, type KerasEmit } from '../types';
import type { IR, IRNode } from './ir';
import { Source, type GeneratedFile } from './source';
import { pyDict, shapeDoc } from './torch';
import type { TrainHyper } from './torchTrain';

function emitCtx(ir: IR, n: IRNode): EmitCtx {
  return {
    framework: 'tensorflow',
    name: n.name,
    id: n.id,
    params: n.params,
    ins: n.ins,
    out: n.out,
    inputNames: ir.inputs.map((i) => i.name),
    imageSize: ir.imageSize,
  };
}

function kerasCode(ir: IR): { node: IRNode; emit: KerasEmit }[] {
  return ir.nodes.map((node) => {
    const r = node.def.emitKeras(emitCtx(ir, node));
    if (isUnsupported(r)) throw new Error(`${node.def.label}: ${r.unsupported}`);
    return { node, emit: r };
  });
}

function kerasLossRefs(expr: string | undefined): string[] {
  if (!expr) return [];
  return [...expr.matchAll(/\b([A-Za-z_][A-Za-z0-9_]*)\b/g)].map((m) => m[1]).filter((id) => id in kerasHelpers);
}

function numpyDummy(n: IRNode, b: number | string): string {
  const s = n.out;
  if (s.kind === 'tokens') return `np.random.randint(0, ${s.vocab}, size=${pyShape(s, 'tensorflow', b)}).astype("int32")`;
  return `np.random.rand${pyShape(s, 'tensorflow', b).replace(/^\(/, '(').replace(/,\)$/, ')')}.astype("float32")`;
}

export function generateKerasModel(ir: IR): GeneratedFile {
  const code = kerasCode(ir);
  const src = new Source();
  const helperIds = code.flatMap((c) => c.emit.helpers ?? []);
  for (const h of ir.heads) helperIds.push(...kerasLossRefs(h.head!.kerasLoss));
  const helpers = resolveHelpers(helperIds, kerasHelpers);
  const imports = new Set<string>();
  for (const c of code) for (const i of c.emit.imports ?? []) imports.add(i);
  for (const id of helpers) for (const i of kerasHelpers[id].imports ?? []) imports.add(i);
  const multi = ir.heads.length > 1;

  const inputsDoc = ir.inputs.map((i) => `    ${i.name}: ${pyShape(i.out, 'tensorflow', 'B')}  # ${shapeDoc(i.out)}`).join('\n');
  const headsDoc = ir.heads.map((h) => `    ${h.name}: ${h.out.kind === 'output' ? h.out.label : ''} (${h.head!.task})`).join('\n');
  src.add(`"""${ir.name} — Keras 3 model (functional API, NHWC) generated by Netloom.

Inputs:
${inputsDoc}
Outputs:
${headsDoc}
Parameters: ${formatCount(ir.analysis.totalParams)} (${ir.analysis.totalParams.toLocaleString('en-US')})

Run \`python model.py\` for a smoke test. Train with \`python train.py\`.
"""`);
  src.blank();
  src.add('from __future__ import annotations');
  src.blank();
  src.add('import keras');
  src.add('import numpy as np');
  src.add('from keras import layers, ops');
  for (const i of [...imports].sort()) src.add(i.startsWith('import ') || i.startsWith('from ') ? i : `import ${i}`);
  src.blank(2);
  const config = {
    inputs: Object.fromEntries(ir.inputs.map((i) => [i.name, pyShape(i.out, 'tensorflow', 'None')])),
    heads: Object.fromEntries(ir.heads.map((h) => [h.name, { task: h.head!.task, ...('classes' in h.params ? { classes: h.params.classes } : {}) }])),
  };
  src.add(`CONFIG = ${pyDict(config, 0)}`);
  src.blank(2);

  const blockHelpers = helpers.filter((id) => (kerasHelpers[id].section ?? 'block') === 'block');
  if (blockHelpers.length) {
    src.add('# ' + '-'.repeat(75));
    src.add('# Building blocks');
    src.add('# ' + '-'.repeat(75));
    src.blank(2);
    for (const id of blockHelpers) {
      src.add(kerasHelpers[id].code, 0, undefined, false);
      src.blank(2);
    }
  }

  src.add('# ' + '-'.repeat(75));
  src.add('# Model');
  src.add('# ' + '-'.repeat(75));
  src.blank(2);
  src.add('def build_model() -> keras.Model:');
  src.add(`"""Construct the model defined in the Netloom graph."""`, 1);
  for (const { node, emit } of code) {
    if (!node.def.isInput) src.add(`# node: ${node.name} → ${shapeDoc(node.out)}`, 1, node.id);
    src.add(`${node.name} = ${emit.expr(node.inputs)}`, 1, node.id);
  }
  const ins = `{${ir.inputs.map((i) => `${py(i.name)}: ${i.name}`).join(', ')}}`;
  const outs = multi ? `{${ir.heads.map((h) => `${py(h.name)}: ${h.name}`).join(', ')}}` : ir.heads[0].name;
  src.add(`return keras.Model(inputs=${ins}, outputs=${outs}, name=${py(ir.name.replace(/[^A-Za-z0-9_]+/g, '_'))})`, 1);
  src.blank(2);

  const lossHelpers = helpers.filter((id) => kerasHelpers[id].section === 'loss' || kerasHelpers[id].section === 'post');
  for (const id of lossHelpers) {
    src.add(kerasHelpers[id].code, 0, undefined, false);
    src.blank(2);
  }

  src.add('def example_inputs(batch_size: int = 2) -> dict[str, np.ndarray]:');
  src.add('"""Random inputs with the declared shapes (NHWC)."""', 1);
  src.add('return {', 1);
  for (const i of ir.inputs) src.add(`${py(i.name)}: ${numpyDummy(i, 'batch_size')},`, 2);
  src.add('}', 1);
  src.blank(2);
  src.add(`if __name__ == "__main__":
    model = build_model()
    outputs = model(example_inputs(), training=False)
    if not isinstance(outputs, dict):
        outputs = {${py(ir.heads[0].name)}: outputs}
    for name, value in outputs.items():
        print(f"{name}: {tuple(value.shape)}")
    print(f"parameters: {model.count_params():,}")`);
  return src.file('model.py');
}

export function generateKerasTrain(ir: IR, hyper: TrainHyper): GeneratedFile {
  const src = new Source();
  const heads = ir.heads;
  const multi = heads.length > 1;
  const lossNames = [...new Set(heads.flatMap((h) => kerasLossRefs(h.head!.kerasLoss)))];
  src.add(`"""Train ${ir.name} with Keras 3 (generated by Netloom).

    python train.py                       # synthetic data: runs immediately
    python train.py --epochs 50 --batch-size 64
    python train.py --epochs 1 --max-steps 2

Replace synthetic_dataset() with a real tf.data pipeline yielding the same structure.
"""`);
  src.blank();
  src.add('from __future__ import annotations');
  src.blank();
  src.add('import argparse');
  src.add('import os');
  src.blank();
  src.add('import keras');
  src.add('import numpy as np');
  src.add('import tensorflow as tf');
  src.blank();
  src.add(`from model import ${['build_model', ...lossNames].join(', ')}`);
  src.blank(2);
  src.add(`EPOCHS = ${hyper.epochs}
BATCH_SIZE = ${hyper.batch}
LR = ${hyper.lr}
WEIGHT_DECAY = ${hyper.weightDecay}
WARMUP_EPOCHS = ${hyper.warmupEpochs}
TRAIN_SAMPLES = 256
VAL_SAMPLES = 64
OUT_DIR = "checkpoints"`);
  src.blank(2);

  const docLines = [
    ...ir.inputs.map((i) => `    ${i.name}: ${pyShape(i.out, 'tensorflow', 'N')}`),
    ...heads.map((h) => `    ${h.name}: ${h.head!.targetDoc}`),
  ].join('\n');
  src.add(`def synthetic_dataset(n: int, batch_size: int, shuffle: bool) -> tf.data.Dataset:
    """Random (inputs, targets) with the exact shapes the model expects.

    Real data must provide the same structure (NHWC images):
${docLines}
    """`);
  src.add('inputs = {', 1);
  for (const i of ir.inputs) src.add(`${py(i.name)}: ${numpyDummy(i, 'n')},`, 2);
  src.add('}', 1);
  if (multi) {
    src.add('targets = {', 1);
    for (const h of heads) src.add(`${py(h.name)}: ${h.head!.kerasTarget},`, 2);
    src.add('}', 1);
  } else src.add(`targets = ${heads[0].head!.kerasTarget}`, 1);
  src.addCont(`ds = tf.data.Dataset.from_tensor_slices((inputs, targets))
    if shuffle:
        ds = ds.shuffle(n)
    return ds.batch(batch_size, drop_remainder=shuffle).prefetch(tf.data.AUTOTUNE)`, 1);
  src.blank(2);

  const lossExpr = multi ? `{${heads.map((h) => `${py(h.name)}: ${h.head!.kerasLoss}`).join(', ')}}` : heads[0].head!.kerasLoss!;
  const metricsExpr = multi ? `{${heads.map((h) => `${py(h.name)}: ${h.head!.kerasMetrics ?? '[]'}`).join(', ')}}` : heads[0].head!.kerasMetrics ?? '[]';
  src.add(`def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--epochs", type=int, default=EPOCHS)
    parser.add_argument("--batch-size", type=int, default=BATCH_SIZE)
    parser.add_argument("--lr", type=float, default=LR)
    parser.add_argument("--max-steps", type=int, default=0, help="limit steps per epoch (0 = full epoch)")
    parser.add_argument("--out", default=OUT_DIR)
    parser.add_argument("--no-export", action="store_true")
    args = parser.parse_args()

    keras.utils.set_random_seed(0)
    os.makedirs(args.out, exist_ok=True)
    train_ds = synthetic_dataset(TRAIN_SAMPLES, args.batch_size, shuffle=True)
    val_ds = synthetic_dataset(VAL_SAMPLES, args.batch_size, shuffle=False)
    steps = args.max_steps or TRAIN_SAMPLES // args.batch_size
    total = max(1, steps * args.epochs)
    schedule = keras.optimizers.schedules.CosineDecay(
        initial_learning_rate=0.0,
        decay_steps=total,
        warmup_target=args.lr,
        warmup_steps=min(WARMUP_EPOCHS * steps, max(1, total // 10)),
    )
    model = build_model()
    model.compile(
        optimizer=keras.optimizers.AdamW(learning_rate=schedule, weight_decay=WEIGHT_DECAY, clipnorm=1.0),
        loss=${lossExpr},
        metrics=${metricsExpr},
    )
    model.fit(
        train_ds,
        validation_data=val_ds,
        epochs=args.epochs,
        steps_per_epoch=steps,
        validation_steps=1 if args.max_steps else None,
        callbacks=[keras.callbacks.ModelCheckpoint(os.path.join(args.out, "best.keras"), save_best_only=True)],
    )
    model.save(os.path.join(args.out, "last.keras"))
    if not args.no_export:
        export_dir = os.path.join(args.out, "saved_model")
        model.export(export_dir)
        converter = tf.lite.TFLiteConverter.from_saved_model(export_dir)
        converter.optimizations = [tf.lite.Optimize.DEFAULT]
        with open(os.path.join(args.out, "model.tflite"), "wb") as f:
            f.write(converter.convert())
        print(f"exported {export_dir} and model.tflite")


if __name__ == "__main__":
    main()`);
  return src.file('train.py');
}
