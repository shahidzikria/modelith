import { formatCount, formatShape, pyShape } from '../shapes';
import { py } from '../py';
import { resolveHelpers, torchHelpers } from '../helpers/registry';
import { isUnsupported, type EmitCtx, type Shape, type TorchEmit } from '../types';
import type { IR, IRNode } from './ir';
import { Source, type GeneratedFile } from './source';

export interface TorchNodeCode {
  node: IRNode;
  emit: TorchEmit;
}

function emitCtx(ir: IR, n: IRNode): EmitCtx {
  return {
    framework: 'pytorch',
    name: n.name,
    id: n.id,
    params: n.params,
    ins: n.ins,
    out: n.out,
    inputNames: ir.inputs.map((i) => i.name),
    imageSize: ir.imageSize,
  };
}

export function torchNodeCode(ir: IR): TorchNodeCode[] {
  return ir.nodes
    .filter((n) => !n.def.isInput)
    .map((node) => {
      const r = node.def.emitTorch(emitCtx(ir, node));
      if (isUnsupported(r)) throw new Error(`${node.def.label}: ${r.unsupported}`);
      return { node, emit: r };
    });
}

/** Python identifiers in an expression that name a known helper (e.g. `SegmentationLoss(21)`). */
export function helperRefs(expr: string | undefined): string[] {
  if (!expr) return [];
  return [...expr.matchAll(/\b([A-Za-z_][A-Za-z0-9_]*)\s*\(/g)].map((m) => m[1]).filter((id) => id in torchHelpers);
}

export function shapeDoc(s: Shape): string {
  return s.kind === 'output' ? s.label : `${s.kind} ${formatShape(s)}`;
}

/** Example tensors for a declared input, batch size `b`. */
export function torchDummy(n: IRNode, b: number | string): string {
  const s = n.out;
  if (s.kind === 'tokens') return `torch.randint(0, ${s.vocab}, ${pyShape(s, 'pytorch', b)})`;
  return `torch.randn${pyShape(s, 'pytorch', b)}`;
}

export function generateTorchModel(ir: IR): GeneratedFile {
  const code = torchNodeCode(ir);
  const src = new Source();

  // ------------------------------------------------------------- helpers
  const helperIds: string[] = [];
  const imports = new Set<string>();
  for (const { emit } of code) {
    helperIds.push(...(emit.helpers ?? []));
    for (const i of emit.imports ?? []) imports.add(i);
  }
  for (const h of ir.heads) {
    helperIds.push(...helperRefs(h.head!.torchLoss));
    if (h.head!.postprocess) helperIds.push(h.head!.postprocess);
  }
  const helpers = resolveHelpers(helperIds, torchHelpers);
  for (const id of helpers) for (const i of torchHelpers[id].imports ?? []) imports.add(i);
  const allCode = [
    ...helpers.map((id) => torchHelpers[id].code),
    ...code.map((c) => c.emit.init ?? ''),
    ...code.map((c) => forwardExpr(c.node, c.emit, 'self.x')),
  ].join('\n');
  const usesMath = /\bmath\./.test(allCode);
  const usesF = /\bF\./.test(allCode);

  // ------------------------------------------------------------- docstring
  const inputsDoc = ir.inputs.map((i) => `    ${i.name}: ${pyShape(i.out, 'pytorch', 'B')}  # ${shapeDoc(i.out)}`).join('\n');
  const headsDoc = ir.heads.map((h) => `    ${h.name}: ${h.out.kind === 'output' ? h.out.label : ''} (${h.head!.task})`).join('\n');
  src.add(`"""${ir.name} — PyTorch model generated by Netloom.

Inputs:
${inputsDoc}
Outputs:
${headsDoc}
Parameters: ${formatCount(ir.analysis.totalParams)} (${ir.analysis.totalParams.toLocaleString('en-US')})
FLOPs: ~${(ir.analysis.totalMacs * 2 / 1e9).toFixed(2)} GFLOPs per sample at the declared input size.

Run \`python model.py\` for a smoke test (builds the model, runs a dummy forward pass,
prints every output shape and the parameter count). Train with \`python train.py\`.
"""`);
  src.blank();
  src.add('from __future__ import annotations');
  src.blank();
  const stdImports = ['collections', 'math'].filter((m) => (m === 'math' ? usesMath : imports.has(m)));
  for (const m of stdImports) src.add(`import ${m}`);
  if (stdImports.length) src.blank();
  src.add('import torch');
  if (usesF) src.add('import torch.nn.functional as F');
  src.add('from torch import nn');
  for (const i of [...imports].filter((x) => x !== 'collections').sort()) src.add(i.startsWith('import ') || i.startsWith('from ') ? i : `import ${i}`);
  src.blank(2);

  // ------------------------------------------------------------- CONFIG
  const config = {
    inputs: Object.fromEntries(ir.inputs.map((i) => [i.name, inputConfig(i)])),
    heads: Object.fromEntries(ir.heads.map((h) => [h.name, { task: h.head!.task, ...headConfig(h) }])),
  };
  src.add(`CONFIG = ${pyDict(config, 0)}`);
  src.blank(2);

  // ------------------------------------------------------------- building blocks
  const blockHelpers = helpers.filter((id) => (torchHelpers[id].section ?? 'block') === 'block');
  if (blockHelpers.length) {
    src.add('# ' + '-'.repeat(75));
    src.add('# Building blocks');
    src.add('# ' + '-'.repeat(75));
    src.blank(2);
    for (const id of blockHelpers) {
      src.add(torchHelpers[id].code, 0, undefined, false);
      src.blank(2);
    }
  }

  // ------------------------------------------------------------- model
  src.add('# ' + '-'.repeat(75));
  src.add('# Model');
  src.add('# ' + '-'.repeat(75));
  src.blank(2);
  if (ir.wrapper) emitWrapped(ir, code, src);
  else emitModule(ir, code, src);
  src.blank(2);

  for (const section of ['post', 'loss'] as const) {
    const ids = helpers.filter((id) => torchHelpers[id].section === section);
    if (!ids.length) continue;
    src.add('# ' + '-'.repeat(75));
    src.add(section === 'post' ? '# Post-processing' : '# Losses');
    src.add('# ' + '-'.repeat(75));
    src.blank(2);
    for (const id of ids) {
      src.add(torchHelpers[id].code, 0, undefined, false);
      src.blank(2);
    }
  }

  // ------------------------------------------------------------- factory + smoke test
  src.add(`def build_model() -> nn.Module:
    """Construct the model defined in the Netloom graph."""
    return GeneratedModel()`);
  src.blank(2);
  src.add('def count_parameters(model: nn.Module) -> int:');
  src.add('return sum(p.numel() for p in model.parameters())', 1);
  src.blank(2);
  src.add('def example_inputs(batch_size: int = 2) -> dict[str, torch.Tensor]:');
  src.add('"""Random inputs with the declared shapes."""', 1);
  src.add('return {', 1);
  for (const i of ir.inputs) src.add(`${py(i.name)}: ${torchDummy(i, 'batch_size')},`, 2);
  src.add('}', 1);
  src.blank(2);
  src.add(`if __name__ == "__main__":
    model = build_model().eval()
    with torch.no_grad():
        outputs = model(**example_inputs())
    if not isinstance(outputs, dict):
        outputs = {${py(ir.heads[0].name)}: outputs}
    for name, value in outputs.items():
        print(f"{name}: {describe(value)}")
    print(f"parameters: {count_parameters(model):,}")`);

  // describe() helper goes right before main for readability.
  const file = src.file('model.py');
  const describe = `def describe(value: object) -> str:
    """Readable shape summary for tensors, lists and dicts of tensors."""
    if isinstance(value, torch.Tensor):
        return str(tuple(value.shape))
    if isinstance(value, dict):
        return "{" + ", ".join(f"{k}: {describe(v)}" for k, v in value.items()) + "}"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(describe(v) for v in value) + "]"
    return type(value).__name__


`;
  file.content = insertBefore(file, 'if __name__ == "__main__":', describe);
  return file;
}

function insertBefore(file: GeneratedFile, marker: string, text: string): string {
  const idx = file.content.indexOf(marker);
  const before = file.content.slice(0, idx);
  const shift = text.split('\n').length - 1;
  const markerLine = before.split('\n').length;
  if (file.lineMap) {
    const next: Record<number, string> = {};
    for (const [k, v] of Object.entries(file.lineMap)) next[Number(k) >= markerLine ? Number(k) + shift : Number(k)] = v;
    file.lineMap = next;
  }
  return before + text + file.content.slice(idx);
}

function forwardExpr(n: IRNode, emit: TorchEmit, selfRef: string): string {
  if (emit.forward) return emit.forward(n.inputs, selfRef);
  return `${selfRef}(${n.inputs.join(', ')})`;
}

function emitModule(ir: IR, code: TorchNodeCode[], src: Source): void {
  const multi = ir.heads.length > 1;
  src.add('class GeneratedModel(nn.Module):');
  src.add(`"""${ir.name}.

forward(${ir.inputs.map((i) => i.name).join(', ')}) returns ${multi ? 'a dict of head outputs' : `the ${ir.heads[0].name} output`}.
"""`, 1);
  src.blank();
  src.add('def __init__(self) -> None:', 1);
  src.add('super().__init__()', 2);
  for (const { node, emit } of code) {
    if (!emit.init) continue;
    src.add(`# node: ${node.name} → ${shapeDoc(node.out)}`, 2, node.id);
    src.add(`self.${node.name} = ${emit.init}`, 2, node.id);
  }
  src.blank();
  const sig = ir.inputs.map((i) => `${i.name}: torch.Tensor`).join(', ');
  src.add(`def forward(self, ${sig}) -> ${multi ? 'dict[str, torch.Tensor]' : 'torch.Tensor'}:`, 1);
  for (const { node, emit } of code) {
    src.add(`${node.name} = ${forwardExpr(node, emit, `self.${node.name}`)}`, 2, node.id);
  }
  if (multi) src.add(`return {${ir.heads.map((h) => `${py(h.name)}: ${h.name}`).join(', ')}}`, 2);
  else src.add(`return ${ir.heads[0].name}`, 2);
}

/** torchvision detectors: everything upstream of the detector becomes `GraphBackbone`. */
function emitWrapped(ir: IR, code: TorchNodeCode[], src: Source): void {
  const det = ir.wrapper!;
  const body = code.filter((c) => c.node.id !== det.id);
  const detCode = code.find((c) => c.node.id === det.id)!;
  const pyr = det.ins[0];
  const outC = pyr.kind === 'pyramid' ? pyr.levels[0].c : 0;
  const levelNames = pyr.kind === 'pyramid' ? pyr.levels.map((_, i) => String(i)) : [];
  const input = ir.inputs[0];

  src.add('class GraphBackbone(nn.Module):');
  src.add(`"""Everything upstream of the detector; returns an OrderedDict of equal-channel feature maps."""`, 1);
  src.blank();
  src.add('def __init__(self) -> None:', 1);
  src.add('super().__init__()', 2);
  src.add(`self.out_channels = ${outC}`, 2);
  for (const { node, emit } of body) {
    if (!emit.init) continue;
    src.add(`# node: ${node.name} → ${shapeDoc(node.out)}`, 2, node.id);
    src.add(`self.${node.name} = ${emit.init}`, 2, node.id);
  }
  src.blank();
  src.add(`def forward(self, ${input.name}: torch.Tensor) -> collections.OrderedDict[str, torch.Tensor]:`, 1);
  for (const { node, emit } of body) src.add(`${node.name} = ${forwardExpr(node, emit, `self.${node.name}`)}`, 2, node.id);
  src.add(`return collections.OrderedDict(zip(${py(levelNames)}, ${det.inputs[0]}))`, 2);
  src.blank(2);

  src.add('class GeneratedModel(nn.Module):');
  src.add(`"""${ir.name}: ${det.def.label} on top of GraphBackbone.

Training: model(${input.name}, targets) → dict of losses.
Inference: model(${input.name}) → list of {"boxes", "labels", "scores"${det.type === 'mask_rcnn' ? ', "masks"' : ''}} per image.
${input.name}: float tensor ${pyShape(input.out, 'pytorch', 'B')} with values in [0, 1] (torchvision normalises internally).
targets: list of {"boxes": (N, 4) xyxy pixels, "labels": (N,) int64 in [0, C-1]${det.type === 'mask_rcnn' ? ', "masks": (N, H, W) uint8' : ''}}.
"""`, 1);
  src.blank();
  src.add('def __init__(self) -> None:', 1);
  src.add('super().__init__()', 2);
  src.add(`# node: ${det.name}`, 2, det.id);
  src.add(`self.${det.name} = ${detCode.emit.init}`, 2, det.id);
  src.blank();
  src.add(`def forward(self, ${input.name}: torch.Tensor, targets: list[dict[str, torch.Tensor]] | None = None):`, 1);
  src.add(`return self.${det.name}(${input.name}, targets)`, 2, det.id);
}

function inputConfig(n: IRNode): Record<string, unknown> {
  const s = n.out;
  if (s.kind === 'image') return { kind: 'image', shape: [s.c, s.h, s.w], norm: n.params.norm };
  if (s.kind === 'tokens') return { kind: 'tokens', length: s.l, vocab: s.vocab, tokenizer: n.params.tokenizer };
  if (s.kind === 'vector') return { kind: 'tabular', features: s.d };
  return { kind: s.kind };
}

function headConfig(h: IRNode): Record<string, unknown> {
  const p = h.params;
  const out: Record<string, unknown> = {};
  if ('classes' in p) out.classes = p.classes;
  if (h.out.kind === 'output' && h.out.dims.length) out.output_shape = h.out.dims;
  if (h.ins[0]?.kind === 'pyramid') out.strides = h.ins[0].levels.map((l) => l.stride);
  return out;
}

/** Pretty Python dict literal with one key per line. */
export function pyDict(v: unknown, level: number): string {
  if (v && typeof v === 'object' && !Array.isArray(v)) {
    const entries = Object.entries(v as Record<string, unknown>);
    if (!entries.length) return '{}';
    const pad = '    '.repeat(level + 1);
    const inner = entries.map(([k, x]) => `${pad}${py(k)}: ${pyDict(x, level + 1)},`).join('\n');
    return `{\n${inner}\n${'    '.repeat(level)}}`;
  }
  if (Array.isArray(v)) return `[${v.map((x) => py(x)).join(', ')}]`;
  return py(v);
}
