import { formatCount, formatShape } from '../shapes';
import { kerasHelpers, resolveHelpers, torchHelpers } from '../helpers/registry';
import type { Project } from '../types';
import { buildIR, type IR } from './ir';
import { generateKerasModel, generateKerasTrain } from './keras';
import { Source, type GeneratedFile } from './source';
import { defaultHyper, generateTorchTrain, type DataHook, type TrainHyper } from './torchTrain';
import { generateTorchModel, torchNodeCode } from './torch';

/** Versions the generated code is tested against in CI. */
export const PINNED = {
  torch: 'torch==2.8.0',
  torchvision: 'torchvision==0.23.0',
  timm: 'timm==1.0.30',
  scipy: 'scipy>=1.11',
  onnx: 'onnx>=1.16',
  torchmetrics: 'torchmetrics>=1.4',
  pycocotools: 'pycocotools>=2.0.7',
  tensorflow: 'tensorflow==2.18.0',
  keras: 'keras>=3.6',
  numpy: 'numpy>=1.26',
  opencv: 'opencv-contrib-python-headless==4.12.0.88',
};

export interface GeneratedProject {
  files: GeneratedFile[];
  ir: IR;
  hyper: TrainHyper;
}

export interface ProjectOptions {
  /** Files and train.py data loading from a linked Preprocessing Studio pipeline. */
  preprocessing?: { files: GeneratedFile[]; train: DataHook };
}

export function generateProject(project: Project, opts: ProjectOptions = {}): GeneratedProject {
  const ir = buildIR(project);
  const hyper = defaultHyper(ir);
  const pre = opts.preprocessing;
  const files: GeneratedFile[] =
    ir.framework === 'pytorch'
      ? [generateTorchModel(ir), generateTorchTrain(ir, hyper, pre?.train)]
      : [generateKerasModel(ir), generateKerasTrain(ir, hyper)];
  files.push(configYaml(ir, hyper), requirements(ir, !!pre), readme(ir, pre?.train.pipelineName), graphJson(project));
  if (pre) files.push(...pre.files.filter((f) => !files.some((x) => x.path === f.path)));
  return { files, ir, hyper };
}

function configYaml(ir: IR, h: TrainHyper): GeneratedFile {
  const s = new Source();
  s.add(`# ${ir.name} — mirrors CONFIG in model.py plus training hyper-parameters.`);
  s.add(`framework: ${ir.framework}`);
  s.add('inputs:');
  for (const i of ir.inputs) {
    const o = i.out;
    s.add(`${i.name}:`, 1);
    if (o.kind === 'image') {
      s.add(`kind: image\nshape: [${o.c}, ${o.h}, ${o.w}]\nnorm: ${i.params.norm}`, 2);
    } else if (o.kind === 'tokens') {
      s.add(`kind: tokens\nlength: ${o.l}\nvocab: ${o.vocab}\ntokenizer: ${i.params.tokenizer}`, 2);
    } else if (o.kind === 'vector') s.add(`kind: tabular\nfeatures: ${o.d}`, 2);
  }
  s.add('heads:');
  for (const hd of ir.heads) {
    s.add(`${hd.name}:`, 1);
    s.add(`task: ${hd.head!.task}`, 2);
    if ('classes' in hd.params) s.add(`classes: ${hd.params.classes}`, 2);
    if (hd.ins[0]?.kind === 'pyramid') s.add(`strides: [${hd.ins[0].levels.map((l) => l.stride).join(', ')}]`, 2);
  }
  s.add('train:');
  s.add(`epochs: ${h.epochs}\nbatch_size: ${h.batch}\nlr: ${h.lr}\nweight_decay: ${h.weightDecay}\nwarmup_epochs: ${h.warmupEpochs}\noptimizer: adamw\nschedule: cosine\namp: true\nema: ${ir.framework === 'pytorch'}`, 1);
  return s.file('config.yaml', 'yaml');
}

function requirements(ir: IR, preprocessing = false): GeneratedFile {
  const reqs = new Set<string>();
  if (preprocessing) {
    reqs.add(PINNED.numpy);
    reqs.add(PINNED.opencv);
  }
  if (ir.framework === 'pytorch') {
    reqs.add(PINNED.torch);
    reqs.add(PINNED.torchvision);
    const code = torchNodeCode(ir);
    const helpers = resolveHelpers(code.flatMap((c) => c.emit.helpers ?? []), torchHelpers);
    const imports = [...code.flatMap((c) => c.emit.imports ?? []), ...helpers.flatMap((id) => torchHelpers[id].imports ?? [])].join('\n');
    if (/timm/.test(imports)) reqs.add(PINNED.timm);
    if (/scipy/.test(imports)) reqs.add(PINNED.scipy);
    reqs.add(PINNED.onnx);
    if (ir.heads.some((h) => h.head!.metric === 'map')) {
      reqs.add(PINNED.torchmetrics);
      reqs.add(PINNED.pycocotools);
    }
  } else {
    reqs.add(PINNED.tensorflow);
    reqs.add(PINNED.keras);
    reqs.add(PINNED.numpy);
    void kerasHelpers;
  }
  for (const n of ir.nodes) for (const r of n.def.requires ?? []) reqs.add(r);
  const s = new Source();
  s.add(`# ${ir.name} — tested with Python 3.12`);
  for (const r of [...reqs].sort()) s.add(r);
  return s.file('requirements.txt', 'text');
}

function readme(ir: IR, pipeline?: string): GeneratedFile {
  const fw = ir.framework === 'pytorch' ? 'PyTorch' : 'TensorFlow / Keras 3';
  const s = new Source();
  s.add(`# ${ir.name}`);
  s.blank();
  s.add(`${fw} model generated by [Modelith](https://github.com/). ${formatCount(ir.analysis.totalParams)} parameters, ~${((ir.analysis.totalMacs * 2) / 1e9).toFixed(2)} GFLOPs per sample.`);
  s.blank();
  s.add('## Architecture');
  s.blank();
  s.add('```');
  const width = Math.max(...ir.nodes.map((n) => n.name.length));
  for (const n of ir.nodes) {
    const from = n.inputs.length ? `← ${n.inputs.join(', ')}` : '(input)';
    const shape = n.out.kind === 'output' ? n.out.label : formatShape(n.out);
    s.add(`${n.name.padEnd(width)}  ${n.def.label.padEnd(26)} ${shape.padEnd(20)} ${from}`);
  }
  s.add('```');
  s.blank();
  s.add('## Usage');
  s.blank();
  s.add('```bash\npip install -r requirements.txt\npython model.py          # smoke test: shapes + parameter count\npython train.py          # trains on synthetic data out of the box\n```');
  s.blank();
  if (pipeline)
    s.add(`Training data is loaded through the preprocessing pipeline **${pipeline}** (\`preprocess.py\`, \`dataset.py\`): put your data under \`data/train\` and \`data/val\` in one of the layouts listed in \`dataset.py\`.`);
  else s.add('Edit `build_datasets()` in `train.py` to plug in real data; the `SyntheticDataset` docstring lists the exact tensor formats.');
  s.blank();
  s.add('## Files');
  s.blank();
  s.add('- `model.py` — architecture, helper blocks, post-processing and losses');
  s.add('- `train.py` — data, training loop, evaluation, export');
  s.add('- `config.yaml` — input sizes, heads and training hyper-parameters');
  s.add('- `graph.json` — the Modelith graph (re-import it to keep editing)');
  s.blank();
  s.add('## Deployment');
  s.blank();
  if (ir.framework === 'pytorch') {
    s.add('- **ONNX → TensorRT**: `trtexec --onnx=checkpoints/model.onnx --fp16 --saveEngine=model.engine`');
    s.add('- **CoreML**: `coremltools.convert(torch.jit.load("checkpoints/model.torchscript.pt"), inputs=[ct.TensorType(shape=...)])`');
    s.add('- **INT8**: calibrate with `trtexec --int8 --calib=...` or `torch.ao.quantization` (PTQ) on a few hundred training images.');
  } else {
    s.add('- **TFLite int8**: use `tf.lite.TFLiteConverter.from_saved_model` with `optimizations=[tf.lite.Optimize.DEFAULT]` and a representative dataset.');
    s.add('- **TF Serving**: serve the exported SavedModel directory directly.');
  }
  for (const h of ir.heads) {
    if (h.def.type === 'yolo_head' || h.def.type === 'ssd_head' || h.def.type === 'detr_head') {
      s.blank();
      s.add(`> ${h.def.label}: exported graphs contain the raw head outputs; run \`${h.head!.postprocess ?? 'postprocess'}\` (decode + NMS) after inference.`);
    }
  }
  return s.file('README.md', 'markdown');
}

function graphJson(project: Project): GeneratedFile {
  const content = JSON.stringify({ ...project, nodes: [...project.nodes].sort((a, b) => a.id.localeCompare(b.id)) }, null, 2) + '\n';
  return { path: 'graph.json', content, language: 'json' };
}
