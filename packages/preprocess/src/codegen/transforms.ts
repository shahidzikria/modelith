// transforms_albumentations.py, transforms_torchvision.py and transforms_tf.py: the same pipeline expressed with
// each library's native transforms where one exists, and the exact preprocess.py step function otherwise.
import { describeMeta } from '../meta';
import { pyFloat } from '../py';
import type { GeneratedFile, Pipeline, StepDef, XCtx } from '../types';
import { registerExportFile, type PipelineExportOptions } from './exports';
import { exportSteps, type ExportStep } from './python';
import { Source } from './source';

/** Native colour ops in these libraries assume RGB; on BGR images the cv2 step function is used instead. */
const COLOR_SENSITIVE = new Set(['color_jitter', 'clahe', 'random_clahe', 'random_grayscale', 'weather', 'hsv_adjust', 'equalize_hist', 'random_equalize']);

function nativeOrUndefined(x: ExportStep, emit: StepDef['emitAlbumentations']): string | undefined {
  if (!emit) return undefined;
  if (COLOR_SENSITIVE.has(x.def.id) && x.in.c === 3 && x.in.space !== 'RGB') return undefined;
  const ctx: XCtx = { in: x.in, out: x.out, fn: x.fn, index: x.index };
  const code = emit(x.step.params, ctx);
  return code?.replace(/\{p\}/g, pyFloat(x.def.kind === 'random' ? (x.step.p ?? 1) : 1));
}

const header = (s: Source, p: Pipeline, lib: string, extra: string) => {
  s.add(`"""${lib} version of the preprocessing pipeline "${p.name.replace(/"/g, "'")}" (generated by Modelith).`);
  s.blank();
  s.add(extra);
  s.add('Steps without a native equivalent call the exact cv2 step function from preprocess.py; those marked');
  s.add('"image only" do not move masks / boxes here; use preprocess.preprocess() when targets must follow them.');
  s.add('"""');
  s.blank();
};

const modeGuard = (x: ExportStep) => (x.step.mode === 'train' ? 'if train:' : x.step.mode === 'inference' ? 'if not train:' : '');

// ----------------------------------------------------------------------------- Albumentations

function albumentations(p: Pipeline, opts: PipelineExportOptions): GeneratedFile | undefined {
  const steps = exportSteps(p, { input: opts.input });
  if (!steps.length) return undefined;
  const s = new Source();
  header(s, p, 'Albumentations', 'Input: the image from preprocess.load_image() (cv2 colour order), plus optional mask / bboxes / keypoints.');
  s.add('import inspect\n\nimport albumentations as A\nimport cv2\nimport numpy as np\n\nimport preprocess as P');
  s.blank(2);
  s.add(`_RNG = np.random.Generator(np.random.PCG64(P.SEED))


def cv2_step(fn, name):
    """Wrap a preprocess.py step function (image only) as an Albumentations transform."""
    params = inspect.signature(fn).parameters

    def image(img, **_):
        kwargs = {}
        if "t" in params:
            kwargs["t"] = P.Targets((img.shape[1], img.shape[0]))
        if "rng" in params:
            kwargs["rng"] = _RNG
        return fn(img, **kwargs)

    return A.Lambda(image=image, name=name, p=1.0)`);
  s.blank(2);
  s.add('def build_transforms(train: bool = True) -> A.Compose:');
  s.add('"""Albumentations Compose for training (augmentations on) or validation / inference."""', 1);
  s.add('t = []', 1);
  for (const x of steps) {
    const native = nativeOrUndefined(x, x.def.emitAlbumentations);
    const guard = modeGuard(x);
    const code = native ? `t.append(${native})` : `t.append(cv2_step(P.${x.fn}, ${JSON.stringify(x.name)}))${x.def.affectsGeometry ? '  # image only' : ''}`;
    const comment = `# ${x.index}. ${x.def.label} → ${describeMeta(x.out)}`;
    s.add(comment, 1, x.step.uid);
    if (guard) {
      s.add(guard, 1, x.step.uid);
      s.add(code, 2, x.step.uid);
    } else s.add(code, 1, x.step.uid);
  }
  s.add(`return A.Compose(
    t,
    bbox_params=A.BboxParams(format="pascal_voc", label_fields=["labels"], min_visibility=P.MIN_BOX_VISIBILITY),
    keypoint_params=A.KeypointParams(format="xy", remove_invisible=False),
)`, 1);
  s.blank(2);
  s.add(`if __name__ == "__main__":
    import sys

    img = P.load_image(sys.argv[1])
    out = build_transforms(train=True)(image=img, bboxes=[], labels=[])["image"]
    print("output:", out.shape, out.dtype)`);
  return s.file('transforms_albumentations.py');
}

// ----------------------------------------------------------------------------- torchvision v2

function torchvision(p: Pipeline, opts: PipelineExportOptions): GeneratedFile | undefined {
  const steps = exportSteps(p, { input: opts.input });
  if (!steps.length) return undefined;
  const s = new Source();
  header(s, p, 'torchvision.transforms.v2', 'Input: the numpy image from preprocess.load_image(); it is converted to a tv_tensors.Image (C, H, W) first.\nBoxes (tv_tensors.BoundingBoxes) and masks (tv_tensors.Mask) follow the native geometric transforms.');
  s.add('import inspect\n\nimport numpy as np\nimport torch\nfrom torchvision import tv_tensors\nfrom torchvision.transforms import v2\n\nimport preprocess as P');
  s.blank(2);
  s.add(`_RNG = np.random.Generator(np.random.PCG64(P.SEED))


class Cv2Step(v2.Transform):
    """Run a preprocess.py step on the image as numpy (H, W, C); boxes / masks pass through unchanged."""

    def __init__(self, fn):
        super().__init__()
        self.fn = fn
        self.params = inspect.signature(fn).parameters

    def transform(self, inpt, params):
        if not isinstance(inpt, tv_tensors.Image):
            return inpt
        img = inpt.permute(1, 2, 0).numpy()
        img = img[..., 0] if img.shape[2] == 1 else img
        kwargs = {}
        if "t" in self.params:
            kwargs["t"] = P.Targets((img.shape[1], img.shape[0]))
        if "rng" in self.params:
            kwargs["rng"] = _RNG
        out = np.ascontiguousarray(self.fn(img, **kwargs))
        out = out[..., None] if out.ndim == 2 else out
        return tv_tensors.Image(torch.from_numpy(out).permute(2, 0, 1))


def to_image(img):
    """numpy (H, W[, C]) → tv_tensors.Image (C, H, W)."""
    img = img[..., None] if img.ndim == 2 else img
    return tv_tensors.Image(torch.from_numpy(np.ascontiguousarray(img)).permute(2, 0, 1))`);
  s.blank(2);
  s.add('def build_transforms(train: bool = True) -> v2.Compose:');
  s.add('"""v2.Compose; call it on to_image(img) (and BoundingBoxes / Mask targets)."""', 1);
  s.add('t = []', 1);
  for (const x of steps) {
    if (x.def.id === 'to_chw') {
      s.add(`# ${x.index}. ${x.def.label}: tensors are already (C, H, W)`, 1, x.step.uid);
      continue;
    }
    const native = nativeOrUndefined(x, x.def.emitTorchvision);
    const guard = modeGuard(x);
    const code = native ? `t.append(${native})` : `t.append(Cv2Step(P.${x.fn}))${x.def.affectsGeometry ? '  # image only' : ''}`;
    s.add(`# ${x.index}. ${x.def.label} → ${describeMeta(x.out)}`, 1, x.step.uid);
    if (guard) {
      s.add(guard, 1, x.step.uid);
      s.add(code, 2, x.step.uid);
    } else s.add(code, 1, x.step.uid);
  }
  s.add('return v2.Compose(t)', 1);
  s.blank(2);
  s.add(`if __name__ == "__main__":
    import sys

    out = build_transforms(train=True)(to_image(P.load_image(sys.argv[1])))
    print("output:", tuple(out.shape), out.dtype)`);
  return s.file('transforms_torchvision.py');
}

// ----------------------------------------------------------------------------- tf.data

function tensorflow(p: Pipeline, opts: PipelineExportOptions): GeneratedFile | undefined {
  const steps = exportSteps(p, { input: opts.input });
  if (!steps.length) return undefined;
  const last = steps[steps.length - 1].out;
  const s = new Source();
  header(s, p, 'tf.data', 'Deterministic steps with a tf.image equivalent run as TensorFlow ops; everything else (and every random step,\nso the seeded NumPy stream is kept) runs through tf.numpy_function around the preprocess.py step.');
  s.add('import inspect\n\nimport numpy as np\nimport tensorflow as tf\n\nimport preprocess as P');
  s.blank(2);
  s.add(`_RNG = np.random.Generator(np.random.PCG64(P.SEED))


def _np_step(fn, dtype):
    """tf.numpy_function wrapper around one preprocess.py step."""
    params = inspect.signature(fn).parameters

    def run(img):
        kwargs = {}
        if "t" in params:
            kwargs["t"] = P.Targets((img.shape[1], img.shape[0]))
        if "rng" in params:
            kwargs["rng"] = _RNG
        return np.ascontiguousarray(fn(img, **kwargs))

    return lambda img: tf.numpy_function(run, [img], dtype)`);
  s.blank(2);
  s.add('def load(path):');
  s.add('"""Read an image exactly like preprocess.load_image (cv2 colour order)."""', 1);
  s.add(`return tf.numpy_function(lambda p: P.load_image(p.decode()), [path], tf.${steps[0].in.dtype})`, 1);
  s.blank(2);
  s.add('def tf_preprocess(img, train: bool = False):');
  s.add(`"""Apply the pipeline to a decoded image tensor. Output: ${describeMeta(last).replace(' CHW', '')} (TensorFlow keeps HWC)."""`, 1);
  for (const x of steps) {
    const native = x.def.kind === 'deterministic' ? nativeOrUndefined(x, x.def.emitTf) : undefined;
    const tfDtype = x.out.dtype === 'float16' ? 'float16' : x.out.dtype;
    const code = native ? `img = ${native}` : `img = _np_step(P.${x.fn}, tf.${tfDtype})(img)${x.def.affectsGeometry ? '  # image only' : ''}`;
    const guard = modeGuard(x);
    s.add(`# ${x.index}. ${x.def.label}`, 1, x.step.uid);
    if (guard) {
      s.add(guard, 1, x.step.uid);
      s.add(code, 2, x.step.uid);
    } else s.add(code, 1, x.step.uid);
  }
  const dims = last.layout === 'CHW' ? [last.h, last.w, last.c] : last.c === 1 ? [last.h, last.w] : [last.h, last.w, last.c];
  s.add(`img = tf.ensure_shape(img, ${last.batch ? '(1, ' : '('}${dims.join(', ')}${dims.length === 1 ? ',' : ''}))`, 1);
  s.add('return img', 1);
  s.blank(2);
  s.add(`def make_dataset(paths, labels=None, train: bool = False, batch_size: int = 32) -> tf.data.Dataset:
    """tf.data pipeline over image files (and optional labels)."""
    ds = tf.data.Dataset.from_tensor_slices(paths if labels is None else (paths, labels))
    if train:
        ds = ds.shuffle(len(paths), seed=P.SEED)
    if labels is None:
        ds = ds.map(lambda p: tf_preprocess(load(p), train), num_parallel_calls=tf.data.AUTOTUNE)
    else:
        ds = ds.map(lambda p, y: (tf_preprocess(load(p), train), y), num_parallel_calls=tf.data.AUTOTUNE)
    return ds.batch(batch_size).prefetch(tf.data.AUTOTUNE)`);
  return s.file('transforms_tf.py');
}

registerExportFile(albumentations);
registerExportFile((p, o) => (o.framework === 'tensorflow' ? tensorflow(p, o) : torchvision(p, o)));
registerExportFile((p, o) => (o.framework === 'tensorflow' ? torchvision(p, o) : tensorflow(p, o)));
