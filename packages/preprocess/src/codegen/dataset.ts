export function datasetPy(p: Pipeline, opts: PipelineExportOptions): GeneratedFile {
  const input = opts.input ?? defaultInputMeta(p);
  const fin = analyzePipeline(p, input, { train: false }).final;
  const batchSteps = p.steps.filter((s) => s.enabled && getStep(s.def)?.batch);
  const s = new Source();
  s.add(`"""Datasets that read images through preprocess.py ("${p.name.replace(/"/g, "'")}", generated by Modelith).

Layouts:
    ImageFolderDataset       root/<class>/*.jpg                          → (image, class index)
    SegmentationDataset      images/*.jpg + masks/<same stem>.png        → (image, mask int64 (H, W))
    YoloDetectionDataset     images/*.jpg + labels/<stem>.txt (YOLO)      → (image, {"boxes": xyxy, "labels"})
    CocoDetectionDataset     images/ + instances.json                    → (image, {"boxes": xyxy, "labels"})

Images come out as ${describeMeta(fin)} (inference) and are returned as torch tensors in (C, H, W).
Training samples use train=True (augmentations on) with a per-worker NumPy generator seeded from
preprocess.SEED and torch.initial_seed(), so runs are reproducible after torch.manual_seed(...).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

import preprocess as P

try:
    import torch
    from torch.utils.data import Dataset
except ImportError:  # TensorFlow-only installs can still use make_tf_dataset()
    torch, Dataset = None, object`);
  s.blank(2);
  s.add(`def to_tensor(img):
    """Final image → float tensor (C, H, W) (the pipeline output may already be CHW)."""
    img = np.ascontiguousarray(img)
    if img.ndim == 2:
        img = img[None]
    elif img.ndim == 3 and ${fin.layout === 'CHW' ? 'False' : 'True'}:  # pipeline output is ${fin.layout}
        img = img.transpose(2, 0, 1)
    t = torch.from_numpy(np.ascontiguousarray(img))
    return t if t.is_floating_point() else t.float()


def find_images(folder):
    return sorted(p for p in Path(folder).rglob("*") if p.suffix.lower() in P.IMAGE_EXTS)


class _Base(Dataset):
    def __init__(self, train: bool):
        self.train = train
        self._rng = None
        self._rng_key = None

    @property
    def rng(self):
        """One generator per DataLoader worker (and per epoch when workers are re-created)."""
        key = (torch.initial_seed(), getattr(torch.utils.data.get_worker_info(), "id", -1))
        if self._rng is None or key != self._rng_key:
            self._rng = np.random.Generator(np.random.PCG64([P.SEED, key[0] % 2**32, key[1] + 1]))
            self._rng_key = key
        return self._rng


class ImageFolderDataset(_Base):
    def __init__(self, root, train: bool = False, classes=None):
        super().__init__(train)
        root = Path(root)
        self.classes = classes or sorted(d.name for d in root.iterdir() if d.is_dir())
        self.samples = [(f, i) for i, c in enumerate(self.classes) for f in find_images(root / c)]

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, i):
        path, label = self.samples[i]
        img, _ = P.preprocess(P.load_image(path), train=self.train, rng=self.rng)
        return to_tensor(img), label


class SegmentationDataset(_Base):
    def __init__(self, images, masks, train: bool = False, mask_suffix: str = ".png"):
        super().__init__(train)
        self.images = find_images(images)
        self.masks = Path(masks)
        self.mask_suffix = mask_suffix

    def __len__(self):
        return len(self.images)

    def __getitem__(self, i):
        path = self.images[i]
        mask = np.fromfile(str(self.masks / (path.stem + self.mask_suffix)), np.uint8)
        mask = P.cv2.imdecode(mask, P.cv2.IMREAD_UNCHANGED)
        mask = mask if mask.ndim == 2 else mask[..., 0]
        img, t = P.preprocess(P.load_image(path), mask=mask, train=self.train, rng=self.rng)
        return to_tensor(img), torch.from_numpy(np.ascontiguousarray(t.mask)).long()


def _detection_target(t):
    b = t.boxes.reshape(-1, t.boxes.shape[1] if t.boxes.ndim == 2 else 5)
    return {"boxes": torch.as_tensor(b[:, :4], dtype=torch.float32), "labels": torch.as_tensor(b[:, 4] if b.shape[1] > 4 else np.zeros(len(b)), dtype=torch.int64)}


class YoloDetectionDataset(_Base):
    """labels/<stem>.txt lines: class cx cy w h (normalised 0..1)."""

    def __init__(self, images, labels, train: bool = False):
        super().__init__(train)
        self.images = find_images(images)
        self.labels = Path(labels)

    def __len__(self):
        return len(self.images)

    def __getitem__(self, i):
        path = self.images[i]
        img = P.load_image(path)
        h, w = img.shape[:2]
        rows = []
        txt = self.labels / (path.stem + ".txt")
        if txt.exists():
            for line in txt.read_text().splitlines():
                v = line.split()
                if len(v) >= 5:
                    c, cx, cy, bw, bh = int(v[0]), *map(float, v[1:5])
                    rows.append([(cx - bw / 2) * w, (cy - bh / 2) * h, (cx + bw / 2) * w, (cy + bh / 2) * h, c])
        img, t = P.preprocess(img, boxes=np.array(rows).reshape(-1, 5), train=self.train, rng=self.rng)
        return to_tensor(img), _detection_target(t)


class CocoDetectionDataset(_Base):
    """COCO instances json: bbox = [x, y, w, h]; category ids are mapped to 0..C-1."""

    def __init__(self, images, ann_file, train: bool = False):
        super().__init__(train)
        coco = json.loads(Path(ann_file).read_text())
        self.cat_ids = sorted(c["id"] for c in coco["categories"])
        self.files = {im["id"]: Path(images) / im["file_name"] for im in coco["images"]}
        self.ids = sorted(self.files)
        self.anns = {i: [] for i in self.ids}
        for a in coco["annotations"]:
            x, y, w, h = a["bbox"]
            self.anns[a["image_id"]].append([x, y, x + w, y + h, self.cat_ids.index(a["category_id"])])

    def __len__(self):
        return len(self.ids)

    def __getitem__(self, i):
        k = self.ids[i]
        img, t = P.preprocess(P.load_image(self.files[k]), boxes=np.array(self.anns[k]).reshape(-1, 5), train=self.train, rng=self.rng)
        return to_tensor(img), _detection_target(t)`);
  if (batchSteps.length) {
    s.blank(2);
    s.add('# Batch-level augmentations from the pipeline (apply them in your collate function / training step).');
    for (const st of batchSteps) {
      s.blank(2);
      s.add(getStep(st.def)!.batch!.emitBatchPython(st.params), 0, st.uid);
    }
  }
  s.blank(2);
  s.add(`def make_tf_dataset(paths, labels=None, train: bool = False, batch_size: int = 32):
    """tf.data equivalent of ImageFolderDataset over explicit paths (images stay HWC for Keras)."""
    import tensorflow as tf

    rng = np.random.Generator(np.random.PCG64(P.SEED))

    def load(p):
        img, _ = P.preprocess(P.load_image(p.decode()), train=train, rng=rng)
        return np.ascontiguousarray(img.transpose(1, 2, 0) if img.ndim == 3 and ${fin.layout === 'CHW' ? 'True' : 'False'} else img).astype(np.float32)

    ds = tf.data.Dataset.from_tensor_slices([str(p) for p in paths] if labels is None else ([str(p) for p in paths], labels))
    fn = (lambda p: tf.numpy_function(load, [p], tf.float32)) if labels is None else (lambda p, y: (tf.numpy_function(load, [p], tf.float32), y))
    return ds.map(fn, num_parallel_calls=tf.data.AUTOTUNE).batch(batch_size).prefetch(tf.data.AUTOTUNE)`);
  return s.file('dataset.py');
}

export interface TrainHook {
  /** Body of build_datasets() in train.py, using dataset.py (indented 4 spaces). */
  buildDatasets: string;
  imports: string[];
}

/**
 * build_datasets() for a Modelith model whose image input is linked to this pipeline.
 * Falls back to the synthetic data when data/ does not exist, so `python train.py --max-steps 2` still runs.
 */
export function trainHook(p: Pipeline, model: { input: string; heads: { name: string; task: string }[] }): TrainHook {
  const head = model.heads[0];
  const task = head?.task;
  const wrap = (ds: string) => `DictDataset(${ds}, ${JSON.stringify(model.input)}, ${JSON.stringify(head?.name ?? 'output')})`;
  let body: string;
  if (task === 'classification' || task === 'multilabel')
    body = [
      'train = D.ImageFolderDataset("data/train", train=True)',
      'val = D.ImageFolderDataset("data/val", train=False, classes=train.classes)',
      `return ${wrap('train')}, ${wrap('val')}`,
    ].join('\n');
  else if (task === 'segmentation' || task === 'dense')
    body = [
      'train = D.SegmentationDataset("data/train/images", "data/train/masks", train=True)',
      'val = D.SegmentationDataset("data/val/images", "data/val/masks", train=False)',
      `return ${wrap('train')}, ${wrap('val')}`,
    ].join('\n');
  else if (task === 'detection')
    body = [
      'train = D.YoloDetectionDataset("data/train/images", "data/train/labels", train=True)',
      'val = D.YoloDetectionDataset("data/val/images", "data/val/labels", train=False)',
      `return ${wrap('train')}, ${wrap('val')}`,
    ].join('\n');
  else body = `# Task "${task}" has no ready-made loader in dataset.py yet; adapt one of its classes.\nreturn SyntheticDataset(256), SyntheticDataset(64)`;
  const guarded = `if not Path("data/train").exists():\n    print("data/train not found: using synthetic data (see dataset.py for the expected layout)")\n    return SyntheticDataset(256), SyntheticDataset(64)\n${body}`;
  return {
    buildDatasets: `    """Real data loaded through the linked preprocessing pipeline "${p.name.replace(/"/g, "'")}" (preprocess.py, dataset.py).

    Training samples use the train pipeline (augmentations), validation the inference pipeline.
    """
${guarded
  .split('\n')
  .map((l) => (l ? `    ${l}` : l))
  .join('\n')}`,
    imports: ['from pathlib import Path', 'import dataset as D'],
  };
}

registerExportFile((p, o) => datasetPy(p, o));
