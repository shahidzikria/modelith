// Regenerates src/steps/index.ts from the step files (one file per step; files starting with _ are shared
// helpers). Run after adding a step:
//   node packages/preprocess/scripts/gen-steps-index.mjs
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const steps = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'steps');
const CATEGORIES = [
  ['io', 'I/O & colour'],
  ['geometric', 'Geometric'],
  ['intensity', 'Intensity'],
  ['filtering', 'Filtering'],
  ['denoising', 'Denoising'],
  ['morphology', 'Morphology'],
  ['edges', 'Edges'],
  ['threshold', 'Threshold'],
  ['frequency', 'Frequency'],
  ['domain', 'Domain'],
  ['augmentation', 'Augmentation'],
  ['tensor', 'Normalise & tensor'],
];
const lines = ['// Generated by scripts/gen-steps-index.mjs: imports every step file so it registers itself.', ''];
for (const [dir, label] of CATEGORIES) {
  let files = [];
  try {
    files = readdirSync(join(steps, dir)).filter((f) => f.endsWith('.ts') && !f.startsWith('_')).sort();
  } catch {
    continue;
  }
  if (!files.length) continue;
  lines.push(`// ${label}`);
  for (const f of files) lines.push(`import './${dir}/${f.replace(/\.ts$/, '')}';`);
}
writeFileSync(join(steps, 'index.ts'), lines.join('\n') + '\n');
console.log(`steps/index.ts: ${lines.filter((l) => l.startsWith('import')).length} step files`);
